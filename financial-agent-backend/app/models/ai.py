"""
AI conversation, message, recommendation, and agent event models.
"""

import enum
import uuid
from datetime import datetime
from typing import Optional, List, TYPE_CHECKING

from sqlalchemy import String, Boolean, ForeignKey, Index, Enum, Text, JSON, DateTime
from sqlalchemy.dialects.postgresql import UUID
from sqlalchemy.orm import Mapped, mapped_column, relationship

from app.core.database import Base, UUIDMixin, TimestampMixin, GUID

if TYPE_CHECKING:
    from app.models.user import User


class MessageRole(str, enum.Enum):
    """Chat message roles."""
    USER = "user"
    ASSISTANT = "assistant"
    SYSTEM = "system"


class RecommendationType(str, enum.Enum):
    """Categories of proactive recommendations."""
    SPENDING = "spending"
    BUDGET = "budget"
    SAVINGS = "savings"
    GOAL = "goal"
    BUSINESS = "business"
    INVESTMENT = "investment"
    GENERAL = "general"


class RecommendationPriority(str, enum.Enum):
    """Recommendation urgency levels."""
    LOW = "low"
    MEDIUM = "medium"
    HIGH = "high"


class AIConversation(Base, UUIDMixin, TimestampMixin):
    """A conversation thread between a user and the AI assistant."""

    __tablename__ = "ai_conversations"

    user_id: Mapped[uuid.UUID] = mapped_column(
        GUID(),
        ForeignKey("users.id", ondelete="CASCADE"),
        nullable=False,
    )
    title: Mapped[Optional[str]] = mapped_column(String(255), nullable=True)

    # ── Relationships ────────────────────────────────────────────────
    user: Mapped["User"] = relationship(back_populates="ai_conversations")
    messages: Mapped[List["AIMessage"]] = relationship(
        back_populates="conversation",
        cascade="all, delete-orphan",
        order_by="AIMessage.created_at.asc()",
    )

    __table_args__ = (
        Index("ix_ai_conversations_user_id", "user_id"),
    )


class AIMessage(Base, UUIDMixin, TimestampMixin):
    """A single message within an AI conversation."""

    __tablename__ = "ai_messages"

    conversation_id: Mapped[uuid.UUID] = mapped_column(
        GUID(),
        ForeignKey("ai_conversations.id", ondelete="CASCADE"),
        nullable=False,
    )
    role: Mapped[MessageRole] = mapped_column(
        Enum(MessageRole, name="message_role", create_constraint=True),
        nullable=False,
    )
    content: Mapped[str] = mapped_column(Text, nullable=False)
    tool_calls: Mapped[Optional[dict]] = mapped_column(JSON, nullable=True)
    tool_results: Mapped[Optional[dict]] = mapped_column(JSON, nullable=True)

    # ── Relationships ────────────────────────────────────────────────
    conversation: Mapped["AIConversation"] = relationship(back_populates="messages")


class AIRecommendation(Base, UUIDMixin, TimestampMixin):
    """
    A proactive AI-generated recommendation or insight.

    Recommendations are generated by the automated agent when it
    identifies actionable patterns in a user's financial data.
    """

    __tablename__ = "ai_recommendations"

    user_id: Mapped[uuid.UUID] = mapped_column(
        GUID(),
        ForeignKey("users.id", ondelete="CASCADE"),
        nullable=False,
    )
    type: Mapped[RecommendationType] = mapped_column(
        Enum(RecommendationType, name="recommendation_type", create_constraint=True),
        nullable=False,
    )
    title: Mapped[str] = mapped_column(String(255), nullable=False)
    content: Mapped[str] = mapped_column(Text, nullable=False)
    reasoning: Mapped[Optional[str]] = mapped_column(Text, nullable=True)
    priority: Mapped[RecommendationPriority] = mapped_column(
        Enum(RecommendationPriority, name="recommendation_priority", create_constraint=True),
        default=RecommendationPriority.MEDIUM,
        nullable=False,
    )
    is_read: Mapped[bool] = mapped_column(Boolean, default=False, nullable=False)
    is_dismissed: Mapped[bool] = mapped_column(Boolean, default=False, nullable=False)
    source_data: Mapped[Optional[dict]] = mapped_column(
        JSON, nullable=True
    )  # What data was analyzed

    # ── Relationships ────────────────────────────────────────────────
    user: Mapped["User"] = relationship(back_populates="ai_recommendations")

    __table_args__ = (
        Index("ix_ai_recommendations_user_read", "user_id", "is_read"),
    )


class AgentEvent(Base, UUIDMixin, TimestampMixin):
    """
    Events that may trigger automated AI analysis.

    When a user creates/updates a financial record, an event is logged
    so the automated agent can process it asynchronously.
    """

    __tablename__ = "agent_events"

    user_id: Mapped[uuid.UUID] = mapped_column(
        GUID(),
        ForeignKey("users.id", ondelete="CASCADE"),
        nullable=False,
    )
    event_type: Mapped[str] = mapped_column(
        String(50), nullable=False
    )  # new_expense, budget_warning, goal_update, etc.
    entity_type: Mapped[str] = mapped_column(
        String(50), nullable=False
    )  # expense, income, budget, goal
    entity_id: Mapped[uuid.UUID] = mapped_column(
        GUID(), nullable=False
    )
    event_metadata: Mapped[Optional[dict]] = mapped_column("metadata", JSON, nullable=True)
    processed: Mapped[bool] = mapped_column(Boolean, default=False, nullable=False)

    __table_args__ = (
        Index("ix_agent_events_user_processed", "user_id", "processed"),
    )
